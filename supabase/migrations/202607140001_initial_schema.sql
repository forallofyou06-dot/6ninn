create or replace function public.get_office_kpi()
returns jsonb
language plpgsql
stable
security definer
set search_path = public, pg_temp
as $$
declare result jsonb;
begin
  if not public.is_office_user() then raise exception '事務局権限が必要です'; end if;
  with event_totals as (
    select e.id, public.effective_event_status(e.id) status,
      1 + (select count(*) from public.participations p where p.event_id = e.id and p.status = '申込') attendees
    from public.events e
  ), tag_totals as (
    select t.name tag, count(*)::integer count
    from public.event_tags et join public.tags t on t.id = et.tag_id
    group by t.name order by count(*) desc limit 10
  )
  select jsonb_build_object(
    'totalEvents', (select count(*) from public.events),
    'completedEvents', (select count(*) from event_totals where status = '開催済'),
    'cancelledEvents', (select count(*) from event_totals where status = '未実施'),
    'eventsThisMonth', (select count(*) from public.events where created_at >= date_trunc('month', now())),
    'totalParticipants', (select count(*) from public.participations where status = '申込'),
    'participantsThisMonth', (select count(*) from public.participations where status = '申込' and applied_at >= date_trunc('month', now())),
    'totalConnectionPairs', (select coalesce(sum(attendees * (attendees - 1) / 2), 0) from event_totals where status = '開催済'),
    'totalFeedbacks', (select count(*) from public.feedbacks),
    'topTags', coalesce((select jsonb_agg(to_jsonb(tag_totals)) from tag_totals), '[]'::jsonb)
  ) into result;
  return result;
end;
$$;

