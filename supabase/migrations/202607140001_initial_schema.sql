create or replace function public.create_report(p_event_id bigint, p_type text, p_content text, p_photo_url text default null)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare event_row public.events%rowtype;
declare report_id bigint;
begin
  select * into event_row from public.events where id = p_event_id;
  if not found then raise exception '会が見つかりません'; end if;
  if p_type not in ('参加者感想', '開催者報告') then raise exception 'レポート種別が不正です'; end if;
  if trim(coalesce(p_content, '')) = '' or char_length(p_content) > 2000 then raise exception '内容は1〜2000文字で入力してください'; end if;
  if public.effective_event_status(p_event_id) not in ('実施確定', '開催済') then raise exception '実施確定後に投稿できます'; end if;
  if p_type = '開催者報告' and event_row.host_id <> auth.uid() then raise exception '開催者報告はホストのみ投稿できます'; end if;
  if p_type = '参加者感想' and not exists (
    select 1 from public.participations where event_id = p_event_id and user_id = auth.uid() and status = '申込'
  ) then raise exception '参加者のみ感想を投稿できます'; end if;

  insert into public.reports(event_id, author_id, type, content, photo_url)
  values (p_event_id, auth.uid(), p_type, trim(p_content), nullif(trim(p_photo_url), ''))
  returning id into report_id;
  return public.report_json(report_id, auth.uid());
exception when unique_violation then
  raise exception 'このレポートはすでに投稿済みです';
end;
$$;

create or replace function public.toggle_report_like(p_report_id bigint)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare now_liked boolean;
declare like_count bigint;
begin
  if not exists(select 1 from public.reports where id = p_report_id) then raise exception 'レポートが見つかりません'; end if;
  if exists(select 1 from public.likes where user_id = auth.uid() and target_type = 'report' and target_id = p_report_id) then
    delete from public.likes where user_id = auth.uid() and target_type = 'report' and target_id = p_report_id;
    now_liked := false;
  else
    insert into public.likes(user_id, target_type, target_id) values (auth.uid(), 'report', p_report_id);
    now_liked := true;
  end if;
  select count(*) into like_count from public.likes where target_type = 'report' and target_id = p_report_id;
  return jsonb_build_object('liked', now_liked, 'likesCount', like_count);
end;
$$;

