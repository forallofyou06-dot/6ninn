create or replace function public.get_my_stats()
returns jsonb
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  with my_completed_events as (
    select e.id, e.host_id
    from public.events e
    where public.effective_event_status(e.id) = '開催済'
      and (e.host_id = auth.uid() or exists (
        select 1 from public.participations p where p.event_id = e.id and p.user_id = auth.uid() and p.status = '申込'
      ))
  ), people as (
    select host_id as user_id from my_completed_events
    union
    select p.user_id from public.participations p join my_completed_events e on e.id = p.event_id where p.status = '申込'
  )
  select jsonb_build_object(
    'participated', (select count(*) from public.participations where user_id = auth.uid() and status = '申込'),
    'hosted', (select count(*) from public.events where host_id = auth.uid()),
    'connections', (select count(*) from people where user_id <> auth.uid())
  );
$$;

create or replace function public.report_json(p_report_id bigint, p_user_id uuid default auth.uid())
returns jsonb
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select jsonb_build_object(
