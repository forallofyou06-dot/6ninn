create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text not null,
  name text,
  department text,
  role text not null default 'member' check (role in ('member', 'office', 'maintainer')),
  interest_tags text[] not null default '{}',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.events (
  id bigint generated by default as identity primary key,
  host_id uuid not null references public.profiles(id) on delete restrict,
  theme text not null check (char_length(theme) between 1 and 100),
  sub_theme text check (sub_theme is null or char_length(sub_theme) <= 200),
  datetime timestamptz not null,
  duration_minutes integer not null default 60 check (duration_minutes between 1 and 120),
  location text not null check (char_length(location) between 1 and 200),
  location_url text check (location_url is null or location_url ~ '^https?://'),
  fee integer not null default 0 check (fee between 0 and 5000),
  capacity integer not null default 6 check (capacity between 2 and 6),
  min_participants integer not null default 2 check (min_participants between 1 and 6 and min_participants <= capacity),
  deadline date not null,
  notes text check (notes is null or char_length(notes) <= 1000),
  status text not null default '募集中' check (status in ('募集中', '実施確定', '開催済', '未実施')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.tags (
  id bigint generated by default as identity primary key,
  name text not null unique check (char_length(name) between 1 and 50)
);

create table if not exists public.event_tags (
  event_id bigint not null references public.events(id) on delete cascade,
  tag_id bigint not null references public.tags(id) on delete cascade,
  primary key (event_id, tag_id)
);

create table if not exists public.participations (
  id bigint generated by default as identity primary key,
  event_id bigint not null references public.events(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  comment text check (comment is null or char_length(comment) <= 500),
  status text not null default '申込' check (status in ('申込', 'キャンセル')),
  applied_at timestamptz not null default now(),
  cancelled_at timestamptz,
  unique (event_id, user_id)
);

create table if not exists public.reports (
  id bigint generated by default as identity primary key,
  event_id bigint not null references public.events(id) on delete cascade,
  author_id uuid not null references public.profiles(id) on delete cascade,
  type text not null check (type in ('参加者感想', '開催者報告')),
  content text not null check (char_length(content) between 1 and 2000),
  photo_url text check (photo_url is null or photo_url ~ '^https?://'),
  created_at timestamptz not null default now(),
  unique (event_id, author_id, type)
);

create table if not exists public.likes (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  target_type text not null check (target_type = 'report'),
  target_id bigint not null references public.reports(id) on delete cascade,
  created_at timestamptz not null default now(),
  unique (user_id, target_type, target_id)
);

create table if not exists public.notifications (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  type text not null,
  content text not null,
  is_read boolean not null default false,
  created_at timestamptz not null default now()
);

create table if not exists public.feedbacks (
  id bigint generated by default as identity primary key,
  from_user_id uuid not null references public.profiles(id) on delete cascade,
  content text not null check (char_length(content) between 1 and 2000),
  event_id bigint references public.events(id) on delete set null,
  created_at timestamptz not null default now()
);

create index if not exists events_datetime_idx on public.events(datetime);
create index if not exists events_host_id_idx on public.events(host_id);
create index if not exists participations_event_status_idx on public.participations(event_id, status);
create index if not exists participations_user_status_idx on public.participations(user_id, status);
create index if not exists reports_event_id_idx on public.reports(event_id);
create index if not exists notifications_user_created_idx on public.notifications(user_id, created_at desc);

