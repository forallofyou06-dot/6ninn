returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  if auth.uid() is null then raise exception 'ログインが必要です'; end if;
  if p_name is null or trim(p_name) = '' or char_length(trim(p_name)) > 100 then
